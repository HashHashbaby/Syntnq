"""Build the web app's bundled samples (M7 task 5): three Creative Commons tracks, 30 s excerpts.

Reads the corpus audio (``data/audio/prototype_30``, never committed), cuts a 30 s excerpt,
analyzes it and writes the five files the app loads plus the excerpt itself to
``web/public/samples/<slug>/`` (git-ignored, regenerated by ``make web-samples``) and an
``index.json`` with the attribution ("Title - Artist (License)") required by the licences.
"""

from __future__ import annotations

import argparse
import csv
import json
import subprocess
import sys
import tempfile
from pathlib import Path

from _corpus import DEFAULT_AUDIO, DEFAULT_MANIFEST, ROOT

from synesthesia.config import load_config
from synesthesia.io import write_result_to
from synesthesia.metadata import SongMetadata
from synesthesia.pipeline import analyze

SAMPLES = ROOT / "web" / "public" / "samples"
EXCERPT_START_S = 40.0
EXCERPT_S = 30.0
EXCERPT_KBPS = 128
# contrasting in character; all CC BY or CC BY-SA (checked against the manifest below)
PICKS = [
    ("track_0078956", "ambient"),
    ("track_0016862", "rock"),
    ("track_0005369", "electronic"),
]
ALLOWED = {"CC BY", "CC BY-SA"}


def synthetic(cfg) -> int:  # type: ignore[no-untyped-def]
    """Samples from the synthetic fixture signals (CI and offline checkouts without corpus audio)."""
    sys.path.insert(0, str(ROOT / "tests"))
    from fixtures import make_signals as ms

    index = []
    with tempfile.TemporaryDirectory() as tmp:
        wavs = ms.write_all(Path(tmp) / "wavs")
        for slug, signal in (
            ("ambient", "chord"),
            ("rock", "click_120bpm"),
            ("electronic", "aba_song"),
        ):
            out = SAMPLES / slug
            out.mkdir(parents=True, exist_ok=True)
            audio = out / "audio.mp3"
            subprocess.run(
                [
                    "ffmpeg",
                    "-v",
                    "error",
                    "-y",
                    "-nostdin",
                    "-i",
                    str(wavs[signal]),
                    "-ac",
                    "1",
                    "-b:a",
                    "96k",
                    str(audio),
                ],
                check=True,
            )
            result = analyze(audio, cfg)
            meta = SongMetadata(
                title=f"Test signal {signal}", artist="synthetic", genre="test", source="synthetic"
            )
            with tempfile.TemporaryDirectory() as t2:
                sd = write_result_to(result, Path(t2) / "s", cfg, meta)
                for name in ("signature.json", "static.bin", "maps.bin", "live.bin", "proto.bin"):
                    (out / name).write_bytes((sd / name).read_bytes())
            index.append(
                {
                    "slug": slug,
                    "song_id": result.song_id,
                    "title": meta.title,
                    "artist": "synthetic",
                    "genre": "test",
                    "duration_s": result.ingest.duration_s,
                    "license": "CC0",
                    "license_url": "https://creativecommons.org/publicdomain/zero/1.0/",
                    "source_url": "",
                    "attribution": f"{meta.title} (generated)",
                    "note": "synthetic",
                    "fingerprint": [float(v) for v in result.fingerprint],
                }
            )
    (SAMPLES / "index.json").write_text(json.dumps(index, indent=2) + "\n", encoding="utf-8")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument(
        "--synthetic", action="store_true", help="use generated signals (no corpus audio needed)"
    )
    args = ap.parse_args()
    cfg = load_config()
    if args.synthetic:
        SAMPLES.mkdir(parents=True, exist_ok=True)
        return synthetic(cfg)
    with DEFAULT_MANIFEST.open(encoding="utf-8", newline="") as f:
        rows = {r["track_id"]: r for r in csv.DictReader(f)}
    SAMPLES.mkdir(parents=True, exist_ok=True)
    index = []
    for track_id, slug in PICKS:
        r = rows[track_id]
        if r["license"] not in ALLOWED:
            raise SystemExit(f"{track_id}: licence {r['license']} may not be bundled")
        src = DEFAULT_AUDIO / f"{track_id}.mp3"
        out = SAMPLES / slug
        out.mkdir(exist_ok=True)
        audio = out / "audio.mp3"
        subprocess.run(
            ["ffmpeg", "-v", "error", "-y", "-nostdin", "-ss", str(EXCERPT_START_S), "-t", str(EXCERPT_S),
             "-i", str(src), "-vn", "-ac", "1", "-b:a", f"{EXCERPT_KBPS}k", "-map_metadata", "-1", str(audio)],
            check=True,
        )  # fmt: skip
        result = analyze(audio, cfg)
        meta = SongMetadata(
            title=r["title"].strip(), artist=r["artist"].strip(), genre=r["genre_group"],
            source="Jamendo (bundled sample)",
        )  # fmt: skip
        with tempfile.TemporaryDirectory() as tmp:
            sd = write_result_to(result, Path(tmp) / "s", cfg, meta)
            for name in ("signature.json", "static.bin", "maps.bin", "live.bin", "proto.bin"):
                (out / name).write_bytes((sd / name).read_bytes())
        index.append(
            {
                "slug": slug,
                "song_id": result.song_id,
                "title": meta.title,
                "artist": meta.artist,
                "genre": meta.genre,
                "duration_s": result.ingest.duration_s,
                "license": r["license"],
                "license_url": r["license_url"],
                "source_url": r["source_url"],
                "attribution": f"{meta.title} - {meta.artist} ({r['license']})",
                "note": f"{EXCERPT_S:.0f} s excerpt starting at {EXCERPT_START_S:.0f} s",
                "fingerprint": [float(v) for v in result.fingerprint],
            }
        )
        sys.stdout.write(f"{slug}: {result.song_id} {meta.title}\n")
    (SAMPLES / "index.json").write_text(json.dumps(index, indent=2) + "\n", encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
